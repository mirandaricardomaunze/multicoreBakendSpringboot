-- Business sectors, phase F2 (docs/STOCK_GRANEL_SPEC.md): bulk stock measured on the pile.
-- Only adds tables; stock corrections go through the existing stock movements as ADJUSTMENT.

create table if not exists bulk_stock_settings (
    id                 bigint generated by default as identity primary key,
    company_id         bigint        not null references companies (id),
    product_id         bigint        not null references products (id),
    tolerance_percent  numeric(5, 2) not null,
    created_at         timestamp     not null,
    updated_at         timestamp,
    created_by         varchar(255),
    constraint uk_bulk_stock_setting unique (company_id, product_id),
    constraint ck_bulk_stock_tolerance check (tolerance_percent >= 0 and tolerance_percent <= 50)
);

create table if not exists bulk_measurements (
    id                  bigint generated by default as identity primary key,
    version             bigint         not null default 0,
    company_id          bigint         not null references companies (id),
    product_id          bigint         not null references products (id),
    warehouse_id        bigint         not null references warehouses (id),
    method              varchar(20)    not null,
    dimension1          numeric(12, 3),
    dimension2          numeric(12, 3),
    dimension3          numeric(12, 3),
    volume_m3           numeric(18, 3),
    measured_quantity   numeric(18, 3) not null,
    pending_pickup      numeric(18, 3) not null,
    system_quantity     numeric(18, 3) not null,
    difference          numeric(18, 3) not null,
    difference_percent  numeric(9, 2)  not null,
    tolerance_percent   numeric(5, 2)  not null,
    status              varchar(20)    not null,
    notes               varchar(500),
    reviewed_by         varchar(255),
    reviewed_at         timestamp,
    rejection_reason    varchar(500),
    stock_movement_id   bigint,
    created_at          timestamp      not null,
    updated_at          timestamp,
    created_by          varchar(255),
    constraint ck_bulk_measurement_method check (method in ('DIRECT', 'BOX', 'HEAP', 'CONE')),
    constraint ck_bulk_measurement_status check (status in ('NO_DIFFERENCE', 'APPLIED', 'PENDING_APPROVAL', 'REJECTED'))
);

create index if not exists idx_bulk_measurement_company_status on bulk_measurements (company_id, status);
