-- Business sectors, phase F4 (docs/CONSIGNACAO_ROTA_SPEC.md): consignment deliveries to resellers.
-- Only adds tables; the "Em consignação" warehouse is an ordinary warehouse created on first use.

create table if not exists consignment_deliveries (
    id                        bigint generated by default as identity primary key,
    company_id                bigint        not null references companies (id),
    number                    varchar(40)   not null,
    delivery_date             date          not null,
    client_id                 bigint        not null references clients (id),
    route                     varchar(80),
    source_warehouse_id       bigint        not null references warehouses (id),
    consignment_warehouse_id  bigint        not null references warehouses (id),
    status                    varchar(20)   not null,
    invoice_id                bigint        references invoices (id),
    settled_at                timestamp,
    settled_by                varchar(255),
    request_key               varchar(64)   not null,
    created_at                timestamp     not null,
    updated_at                timestamp,
    created_by                varchar(255),
    constraint uk_consignment_request unique (company_id, request_key)
);

create table if not exists consignment_lines (
    id             bigint generated by default as identity primary key,
    delivery_id    bigint         not null references consignment_deliveries (id),
    product_id     bigint         not null references products (id),
    delivered_qty  numeric(14, 3) not null,
    returned_qty   numeric(14, 3) not null default 0,
    damaged_qty    numeric(14, 3) not null default 0,
    created_at     timestamp      not null,
    updated_at     timestamp,
    created_by     varchar(255)
);

create index if not exists idx_consignment_company_status on consignment_deliveries (company_id, status);
