-- Business sectors, phase F5 (docs/BASCULA_CAMIAO_SPEC.md): truck scale weighing tickets.
-- Only adds a table.

create table if not exists weighing_tickets (
    id             bigint generated by default as identity primary key,
    company_id     bigint         not null references companies (id),
    number         varchar(40)    not null,
    status         varchar(20)    not null,
    direction      varchar(10)    not null,
    plate          varchar(20)    not null,
    driver         varchar(120),
    counterparty   varchar(160),
    product_id     bigint         references products (id),
    reference      varchar(80),
    first_weight   numeric(14, 3) not null,
    first_at       timestamp      not null,
    second_weight  numeric(14, 3),
    second_at      timestamp,
    net_weight     numeric(14, 3),
    manual_weight  boolean        not null default false,
    notes          varchar(300),
    closed_by      varchar(255),
    request_key    varchar(64)    not null,
    created_at     timestamp      not null,
    updated_at     timestamp,
    created_by     varchar(255),
    constraint uk_weighing_ticket_request unique (company_id, request_key)
);

create index if not exists idx_weighing_tickets_company_status on weighing_tickets (company_id, status);
