-- Business sectors, phase F5 (docs/VARIANTES_ARTIGO_SPEC.md): product variant families.
-- Only adds tables; every variant is an ordinary row in products.

create table if not exists product_families (
    id                   bigint generated by default as identity primary key,
    company_id           bigint        not null references companies (id),
    name                 varchar(120)  not null,
    sku_prefix           varchar(20)   not null,
    attribute1           varchar(40)   not null,
    attribute2           varchar(40),
    template_product_id  bigint        not null references products (id),
    active               boolean       not null default true,
    created_at           timestamp     not null,
    updated_at           timestamp,
    created_by           varchar(255),
    constraint uk_product_family_prefix unique (company_id, sku_prefix)
);

create table if not exists product_variants (
    id          bigint generated by default as identity primary key,
    family_id   bigint       not null references product_families (id),
    product_id  bigint       not null references products (id),
    value1      varchar(30)  not null,
    value2      varchar(30),
    created_at  timestamp    not null,
    updated_at  timestamp,
    created_by  varchar(255),
    constraint uk_product_variant_product unique (product_id)
);
