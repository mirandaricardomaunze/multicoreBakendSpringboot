-- Business sectors, phase F2 (docs/OBRAS_CLIENTE_SPEC.md): client projects or construction sites.
-- Only adds tables; orders are linked through customer_project_orders, so customer_orders is untouched.

create table if not exists customer_projects (
    id          bigint generated by default as identity primary key,
    company_id  bigint        not null references companies (id),
    client_id   bigint        not null references clients (id),
    code        varchar(30)   not null,
    name        varchar(150)  not null,
    address     varchar(300),
    contact     varchar(150),
    active      boolean       not null default true,
    created_at  timestamp     not null,
    updated_at  timestamp,
    created_by  varchar(255),
    constraint uk_customer_project_code unique (company_id, code)
);

create table if not exists customer_project_orders (
    id          bigint generated by default as identity primary key,
    project_id  bigint        not null references customer_projects (id),
    order_id    bigint        not null references customer_orders (id),
    created_at  timestamp     not null,
    updated_at  timestamp,
    created_by  varchar(255),
    constraint uk_customer_project_order unique (order_id)
);
