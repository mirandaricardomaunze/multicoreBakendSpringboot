-- Business sectors, phase F2 (docs/ADIANTAMENTOS_SPEC.md): customer advances.
-- Only adds a table that links fiscal documents already issued by the ordinary services
-- (advance invoice, receipt, credit note and offset receipt). No existing table changes.

create table if not exists customer_advances (
    id                  bigint generated by default as identity primary key,
    company_id          bigint         not null references companies (id),
    client_id           bigint         not null references clients (id),
    order_id            bigint         references customer_orders (id),
    amount              numeric(14, 2) not null,
    status              varchar(20)    not null,
    advance_invoice_id  bigint         not null references invoices (id),
    receipt_id          bigint         not null references receipts (id),
    applied_invoice_id  bigint         references invoices (id),
    credit_note_id      bigint         references credit_notes (id),
    offset_receipt_id   bigint         references receipts (id),
    applied_at          timestamp,
    applied_by          varchar(255),
    notes               varchar(300),
    request_key         varchar(64)    not null,
    created_at          timestamp      not null,
    updated_at          timestamp,
    created_by          varchar(255),
    constraint uk_customer_advance_request unique (company_id, request_key)
);

create index if not exists idx_customer_advances_company_status on customer_advances (company_id, status);
create index if not exists idx_customer_advances_client on customer_advances (client_id);
