-- Business sectors, phase F4 (docs/ENCOMENDAS_PERSONALIZADAS_SPEC.md): delivery and personalisation of orders.
-- Only adds a table; the delivery date stays in customer_orders.expected_delivery_date.

create table if not exists order_customizations (
    id                bigint generated by default as identity primary key,
    company_id        bigint        not null references companies (id),
    order_id          bigint        not null references customer_orders (id),
    delivery_time     time,
    delivery_mode     varchar(20)   not null,
    delivery_address  varchar(300),
    contact_phone     varchar(40),
    personalization   varchar(1000),
    image_data        bytea,
    stage             varchar(20)   not null,
    sent_to_plan_at   timestamp,
    created_at        timestamp     not null,
    updated_at        timestamp,
    created_by        varchar(255),
    constraint uk_order_customization_order unique (order_id)
);
