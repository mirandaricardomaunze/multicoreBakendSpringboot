-- Business sectors, phase F4 (docs/PLANO_PRODUCAO_SPEC.md): daily production plan of the bakery.
-- Only adds tables; recipes are the existing manufacturing_boms.

create table if not exists production_plans (
    id           bigint generated by default as identity primary key,
    company_id   bigint        not null references companies (id),
    warehouse_id bigint        not null references warehouses (id),
    plan_date    date          not null,
    status       varchar(20)   not null,
    notes        varchar(300),
    closed_at    timestamp,
    closed_by    varchar(255),
    created_at   timestamp     not null,
    updated_at   timestamp,
    created_by   varchar(255),
    constraint uk_production_plan_day unique (company_id, warehouse_id, plan_date)
);

create table if not exists production_plan_lines (
    id            bigint generated by default as identity primary key,
    plan_id       bigint         not null references production_plans (id),
    bom_id        bigint         not null references manufacturing_boms (id),
    product_id    bigint         not null references products (id),
    planned_qty   numeric(14, 3) not null default 0,
    produced_qty  numeric(14, 3) not null default 0,
    leftover_qty  numeric(14, 3) not null default 0,
    sort_order    integer        not null default 0,
    created_at    timestamp      not null,
    updated_at    timestamp,
    created_by    varchar(255)
);

create table if not exists production_runs (
    id               bigint generated by default as identity primary key,
    company_id       bigint         not null references companies (id),
    line_id          bigint         not null references production_plan_lines (id),
    quantity         numeric(14, 3) not null,
    batch_number     varchar(60)    not null,
    expiration_date  date,
    ingredient_cost  numeric(14, 2) not null default 0,
    total_cost       numeric(14, 2) not null default 0,
    unit_cost        numeric(14, 4) not null default 0,
    request_key      varchar(64)    not null,
    created_at       timestamp      not null,
    updated_at       timestamp,
    created_by       varchar(255),
    constraint uk_production_run_request unique (company_id, request_key)
);
