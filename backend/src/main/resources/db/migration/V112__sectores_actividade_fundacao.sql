-- Business sectors, phase F1 (docs/SECTORES_ACTIVIDADE_SPEC.md):
-- company activity profiles, units of measure and price lists.
-- Only adds tables and one nullable column, so no existing data changes meaning.

-- SA-C01: company activity profiles
create table if not exists company_activity_profiles (
    id          bigint generated by default as identity primary key,
    company_id  bigint       not null references companies (id),
    profile     varchar(40)  not null,
    created_at  timestamp    not null,
    updated_at  timestamp,
    created_by  varchar(255),
    constraint uk_company_activity_profile unique (company_id, profile)
);

-- SA-C02: unit catalogue (system units are seeded at start-up by SystemUnitCatalogSeeder)
create table if not exists units_of_measure (
    id                bigint generated by default as identity primary key,
    company_id        bigint        references companies (id),
    code              varchar(20)   not null,
    name              varchar(80)   not null,
    symbol            varchar(20),
    dimension         varchar(20)   not null,
    dimension_factor  numeric(18, 6),
    decimals          integer       not null,
    system_unit       boolean       not null,
    active            boolean       not null default true,
    created_at        timestamp     not null,
    updated_at        timestamp,
    created_by        varchar(255),
    constraint uk_unit_company_code unique (company_id, code)
);

-- System units are unique by code (a null company_id is not covered by the constraint above)
create unique index if not exists uk_unit_system_code on units_of_measure (code) where company_id is null;

-- SA-C02: explicit product base unit (null means UN, or KG for weighed products)
alter table products add column if not exists base_unit_code varchar(20);

-- SA-C02: alternative units per product
create table if not exists product_units (
    id                bigint generated by default as identity primary key,
    product_id        bigint         not null references products (id),
    unit_id           bigint         not null references units_of_measure (id),
    factor_to_base    numeric(18, 6) not null,
    barcode           varchar(64),
    sellable          boolean        not null default true,
    purchasable       boolean        not null default true,
    default_sale      boolean        not null default false,
    default_purchase  boolean        not null default false,
    created_at        timestamp      not null,
    updated_at        timestamp,
    created_by        varchar(255),
    constraint uk_product_unit unique (product_id, unit_id),
    constraint uk_product_unit_barcode unique (barcode),
    constraint ck_product_unit_factor check (factor_to_base > 0)
);

-- SA-C03: price lists
create table if not exists price_lists (
    id           bigint generated by default as identity primary key,
    version      bigint        not null default 0,
    company_id   bigint        not null references companies (id),
    code         varchar(30)   not null,
    name         varchar(120)  not null,
    description  varchar(500),
    valid_from   date,
    valid_to     date,
    active       boolean       not null default true,
    created_at   timestamp     not null,
    updated_at   timestamp,
    created_by   varchar(255),
    constraint uk_price_list_company_code unique (company_id, code)
);

create table if not exists price_list_items (
    id             bigint generated by default as identity primary key,
    price_list_id  bigint         not null references price_lists (id),
    product_id     bigint         not null references products (id),
    min_quantity   numeric(18, 3) not null default 0,
    price          numeric(19, 2) not null,
    created_at     timestamp      not null,
    updated_at     timestamp,
    created_by     varchar(255),
    constraint uk_price_list_item unique (price_list_id, product_id, min_quantity),
    constraint ck_price_list_item_price check (price > 0),
    constraint ck_price_list_item_min check (min_quantity >= 0)
);

create index if not exists idx_price_list_item_lookup on price_list_items (price_list_id, product_id);

create table if not exists client_price_lists (
    id             bigint generated by default as identity primary key,
    company_id     bigint       not null references companies (id),
    client_id      bigint       not null references clients (id),
    price_list_id  bigint       not null references price_lists (id),
    created_at     timestamp    not null,
    updated_at     timestamp,
    created_by     varchar(255),
    constraint uk_client_price_list unique (company_id, client_id)
);
