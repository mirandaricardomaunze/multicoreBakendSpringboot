CREATE TABLE document_print_controls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    document_type VARCHAR(40) NOT NULL,
    document_id BIGINT NOT NULL,
    print_count INTEGER NOT NULL DEFAULT 0,
    printed_at TIMESTAMP,
    last_printed_by VARCHAR(80),
    last_authorized_by VARCHAR(80),
    last_reason VARCHAR(500),
    last_terminal VARCHAR(120),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    CONSTRAINT uk_document_print_control UNIQUE (company_id, document_type, document_id)
);

CREATE INDEX idx_document_print_control_lookup
    ON document_print_controls (company_id, document_type, document_id);
