-- Business sectors, phase F3 (docs/DESMANCHA_SPEC.md): butchery carcass breakdown.
-- Adds the breakdown tables and the PRODUCTION stock movement type (carcass out, cuts in).

ALTER TABLE stock_movements DROP CONSTRAINT IF EXISTS stock_movements_movement_type_check;
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_movement_type_check
    CHECK (movement_type IN ('PURCHASE', 'ENTRY', 'SALE', 'TRANSFER', 'ADJUSTMENT', 'RETURN', 'REVERSAL', 'WASTE', 'PRODUCTION'));

create table if not exists breakdown_templates (
    id                  bigint generated by default as identity primary key,
    company_id          bigint        not null references companies (id),
    name                varchar(120)  not null,
    source_product_id   bigint        not null references products (id),
    loss_tolerance_pct  numeric(6, 2) not null default 0,
    active              boolean       not null default true,
    created_at          timestamp     not null,
    updated_at          timestamp,
    created_by          varchar(255)
);

create table if not exists breakdown_template_lines (
    id                  bigint generated by default as identity primary key,
    template_id         bigint        not null references breakdown_templates (id),
    product_id          bigint        not null references products (id),
    expected_yield_pct  numeric(6, 2) not null default 0,
    sort_order          integer       not null default 0,
    created_at          timestamp     not null,
    updated_at          timestamp,
    created_by          varchar(255)
);

create table if not exists carcass_breakdowns (
    id                   bigint generated by default as identity primary key,
    company_id           bigint         not null references companies (id),
    number               varchar(40)    not null,
    warehouse_id         bigint         not null references warehouses (id),
    template_id          bigint         references breakdown_templates (id),
    source_product_id    bigint         not null references products (id),
    input_kg             numeric(14, 3) not null,
    input_cost           numeric(14, 2) not null,
    output_kg            numeric(14, 3) not null,
    loss_tolerance_pct   numeric(6, 2),
    status               varchar(20)    not null,
    reference            varchar(120),
    notes                varchar(300),
    cancellation_reason  varchar(300),
    cancelled_at         timestamp,
    cancelled_by         varchar(255),
    request_key          varchar(64)    not null,
    created_at           timestamp      not null,
    updated_at           timestamp,
    created_by           varchar(255),
    constraint uk_carcass_breakdown_request unique (company_id, request_key)
);

create table if not exists carcass_breakdown_lines (
    id                  bigint generated by default as identity primary key,
    breakdown_id        bigint         not null references carcass_breakdowns (id),
    product_id          bigint         not null references products (id),
    kg                  numeric(14, 3) not null,
    unit_sale_price     numeric(14, 2) not null default 0,
    allocated_cost      numeric(14, 2) not null default 0,
    cost_per_kg         numeric(14, 4) not null default 0,
    expected_yield_pct  numeric(6, 2),
    created_at          timestamp      not null,
    updated_at          timestamp,
    created_by          varchar(255)
);

create index if not exists idx_carcass_breakdowns_company on carcass_breakdowns (company_id, created_at);
