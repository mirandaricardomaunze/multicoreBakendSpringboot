-- Business sectors, phase F5 (docs/VASILHAME_RETORNAVEIS_SPEC.md): returnables account per client.
-- Only adds tables; "Vasilhame em clientes" is an ordinary warehouse created on first use.

create table if not exists returnable_items (
    id          bigint generated by default as identity primary key,
    company_id  bigint       not null references companies (id),
    product_id  bigint       not null references products (id),
    active      boolean      not null default true,
    created_at  timestamp    not null,
    updated_at  timestamp,
    created_by  varchar(255),
    constraint uk_returnable_item_product unique (company_id, product_id)
);

create table if not exists returnable_movements (
    id             bigint generated by default as identity primary key,
    company_id     bigint         not null references companies (id),
    client_id      bigint         not null references clients (id),
    item_id        bigint         not null references returnable_items (id),
    movement_type  varchar(20)    not null,
    quantity       numeric(14, 3) not null,
    reference      varchar(80),
    invoice_id     bigint         references invoices (id),
    notes          varchar(300),
    request_key    varchar(64)    not null,
    created_at     timestamp      not null,
    updated_at     timestamp,
    created_by     varchar(255),
    constraint uk_returnable_movement_request unique (company_id, request_key)
);

create index if not exists idx_returnable_movements_account on returnable_movements (company_id, client_id, item_id);
