-- Business sectors, phase F2 (docs/MATERIAL_POR_LEVANTAR_SPEC.md):
-- paid material collected over time. Only adds tables; invoices and stock are untouched.

create table if not exists pickup_accounts (
    id          bigint generated by default as identity primary key,
    version     bigint        not null default 0,
    company_id  bigint        not null references companies (id),
    invoice_id  bigint        not null references invoices (id),
    deadline    date,
    status      varchar(20)   not null,
    notes       varchar(500),
    created_at  timestamp     not null,
    updated_at  timestamp,
    created_by  varchar(255),
    constraint uk_pickup_account_invoice unique (invoice_id),
    constraint ck_pickup_account_status check (status in ('OPEN', 'COMPLETED', 'CANCELLED'))
);

create index if not exists idx_pickup_account_company_status on pickup_accounts (company_id, status);

create table if not exists material_pickups (
    id                  bigint generated by default as identity primary key,
    company_id          bigint        not null references companies (id),
    account_id          bigint        not null references pickup_accounts (id),
    pickup_number       varchar(40)   not null,
    picked_at           timestamp     not null,
    collector_name      varchar(150)  not null,
    collector_document  varchar(60),
    vehicle_plate       varchar(30),
    notes               varchar(500),
    request_key         varchar(80),
    status              varchar(20)   not null,
    cancel_reason       varchar(500),
    created_at          timestamp     not null,
    updated_at          timestamp,
    created_by          varchar(255),
    constraint uk_material_pickup_number unique (company_id, pickup_number),
    constraint uk_material_pickup_request unique (company_id, request_key),
    constraint ck_material_pickup_status check (status in ('ISSUED', 'CANCELLED'))
);

create table if not exists material_pickup_lines (
    id               bigint generated by default as identity primary key,
    pickup_id        bigint          not null references material_pickups (id),
    invoice_line_id  bigint          not null references invoice_lines (id),
    quantity         numeric(18, 3)  not null,
    constraint ck_material_pickup_line_quantity check (quantity > 0)
);

create index if not exists idx_material_pickup_line_pickup on material_pickup_lines (pickup_id);
