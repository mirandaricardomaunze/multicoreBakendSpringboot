-- Business sectors, phase F3 (docs/VALIDADES_REMARCACAO_SPEC.md): markdown rules by days before expiry.
-- Only adds a table; markdowns are ordinary store promotions and write-offs ordinary stock wastes.

create table if not exists markdown_rules (
    id             bigint generated by default as identity primary key,
    company_id     bigint        not null references companies (id),
    category_id    bigint        references product_categories (id),
    days_before    integer       not null,
    percent_value  numeric(5, 2) not null,
    active         boolean       not null default true,
    created_at     timestamp     not null,
    updated_at     timestamp,
    created_by     varchar(255)
);

create index if not exists idx_markdown_rules_company on markdown_rules (company_id);
