/**
 * Harness FX-11 (docs/MOEDA_ESTRANGEIRA_IMPORTACAO_SPEC.md §3.4): o plano de contas tem 66/6601 e
 * 76/7601 para a diferença cambial, nas empresas novas e nas que já têm plano, sem duplicar contas.
 */
class ExchangeDifferenceAccountsTest {

    private static final List<String> FX_CODES = List.of("66", "6601", "76", "7601");

    private static Map<String, PgcNirfChart.Seed> seedsByCode() {
        return PgcNirfChart.accounts().stream()
                .collect(Collectors.toMap(PgcNirfChart.Seed::code, Function.identity()));
    }

    @Test
    void planoSemeado_temContasDeDiferencaCambial() {
        Map<String, PgcNirfChart.Seed> seeds = seedsByCode();

        assertThat(PgcNirfChart.EXCHANGE_LOSS).isEqualTo("6601");
        assertThat(PgcNirfChart.EXCHANGE_GAIN).isEqualTo("7601");
        assertThat(seeds.get("66")).isEqualTo(
                new PgcNirfChart.Seed("66", "Custos financeiros", AccountNature.DEVEDORA, false));
        assertThat(seeds.get("6601")).isEqualTo(new PgcNirfChart.Seed("6601",
                "Diferenças de câmbio desfavoráveis", AccountNature.DEVEDORA, true));
        assertThat(seeds.get("76")).isEqualTo(
                new PgcNirfChart.Seed("76", "Proveitos financeiros", AccountNature.CREDORA, false));
        assertThat(seeds.get("7601")).isEqualTo(new PgcNirfChart.Seed("7601",
                "Diferenças de câmbio favoráveis", AccountNature.CREDORA, true));
    }

    @Test
    void empresaNova_recebeContasDeDiferencaCambial() {
        AccountRepository repository = mock(AccountRepository.class);
        when(repository.findByCompanyIdOrderByCode(anyLong())).thenReturn(List.of());

        new ChartOfAccountsMutationService(repository, mock(CompanyService.class)).seedChartFor(company(9L));

        assertThat(saved(repository)).extracting(Account::getCode).containsAll(FX_CODES);
    }

    @Test
    void empresaComPlano_semearSoAcrescentaAsContasEmFalta() {
        AccountRepository repository = mock(AccountRepository.class);
        List<Account> existing = PgcNirfChart.accounts().stream()
                .filter(seed -> !FX_CODES.contains(seed.code()) || seed.code().equals("66"))
                .map(seed -> account(seed.code())).toList();
        when(repository.findByCompanyIdOrderByCode(4L)).thenReturn(existing);

        new ChartOfAccountsMutationService(repository, mock(CompanyService.class)).seedChartFor(company(4L));

        assertThat(saved(repository)).extracting(Account::getCode)
                .containsExactlyInAnyOrder("6601", "76", "7601");
    }

    @Test
    void migracao_acrescentaContasNasEmpresasComPlano_semDuplicar_eERepetivel() throws Exception {
        try (Connection db = DriverManager.getConnection("jdbc:h2:mem:fx11;MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
             Statement st = db.createStatement()) {
            st.execute("create table companies (id bigint primary key)");
            st.execute("""
                    create table accounts (
                        id bigint generated by default as identity primary key,
                        code varchar(20) not null, name varchar(200) not null,
                        company_id bigint not null references companies (id),
                        account_class varchar(40) not null, nature varchar(10) not null,
                        postable boolean not null default true, active boolean not null default true,
                        parent_code varchar(20), created_at timestamp not null, updated_at timestamp,
                        created_by varchar(255),
                        constraint uk_accounts_company_code unique (company_id, code))""");
            st.execute("insert into companies (id) values (1), (2), (3)");
            st.execute("insert into accounts (code, name, company_id, account_class, nature, created_at) values "
                    + "('6101', 'CMV', 1, 'CUSTOS_E_PERDAS', 'DEVEDORA', current_timestamp), "
                    + "('66', 'Custos financeiros (já existia)', 1, 'CUSTOS_E_PERDAS', 'DEVEDORA', current_timestamp), "
                    + "('6101', 'CMV', 2, 'CUSTOS_E_PERDAS', 'DEVEDORA', current_timestamp)");

            String script = migrationFile().toAbsolutePath().toString().replace("'", "''");
            String runScript = "runscript from '" + script + "' charset 'UTF-8'";
            st.execute(runScript);
            st.execute(runScript);

            assertThat(codes(st, 1)).containsExactlyInAnyOrder("6101", "66", "6601", "76", "7601");
            assertThat(codes(st, 2)).containsExactlyInAnyOrder("6101", "66", "6601", "76", "7601");
            assertThat(codes(st, 3)).isEmpty();
            try (ResultSet rs = st.executeQuery("select name from accounts where company_id = 1 and code = '66'")) {
                rs.next();
                assertThat(rs.getString(1)).isEqualTo("Custos financeiros (já existia)");
            }

            Map<String, PgcNirfChart.Seed> seeds = seedsByCode();
            try (ResultSet rs = st.executeQuery("select code, name, account_class, nature, postable, active, "
                    + "parent_code from accounts where company_id = 2 and code <> '6101'")) {
                while (rs.next()) {
                    String code = rs.getString("code");
                    PgcNirfChart.Seed seed = seeds.get(code);
                    assertThat(rs.getString("name")).isEqualTo(seed.name());
                    assertThat(rs.getString("account_class")).isEqualTo(AccountClass.ofCode(code).name());
                    assertThat(rs.getString("nature")).isEqualTo(seed.nature().name());
                    assertThat(rs.getBoolean("postable")).isEqualTo(seed.postable());
                    assertThat(rs.getBoolean("active")).isTrue();
                    assertThat(rs.getString("parent_code")).isEqualTo(Account.parentCodeOf(code));
                }
            }
        }
    }

    private static List<String> codes(Statement st, long companyId) throws SQLException {
        List<String> codes = new ArrayList<>();
        try (ResultSet rs = st.executeQuery("select code from accounts where company_id = " + companyId)) {
            while (rs.next()) codes.add(rs.getString(1));
        }
        return codes;
    }

    private static Path migrationFile() throws IOException {
        Path dir = Path.of("src/main/resources/db/migration");
        if (!Files.isDirectory(dir)) dir = Path.of("backend").resolve(dir);
        try (Stream<Path> files = Files.list(dir)) {
            List<Path> matches = files
                    .filter(p -> p.getFileName().toString().endsWith("__exchange_difference_accounts.sql")).toList();
            assertThat(matches).as("uma migração Flyway semeia 66/6601/76/7601 nas empresas com plano").hasSize(1);
            return matches.get(0);
        }
    }

    private static Company company(Long id) {
        Company company = new Company();
        company.setId(id);
        return company;
    }

    private static Account account(String code) {
        Account account = new Account();
        account.setCode(code);
        return account;
    }

    @SuppressWarnings("unchecked")
    private static List<Account> saved(AccountRepository repository) {
        ArgumentCaptor<List<Account>> captor = ArgumentCaptor.forClass(List.class);
        verify(repository).saveAll(captor.capture());
        return captor.getValue();
    }
}
